"""Build data/walks.js from tools/walks-source.json.

Walks without a hand-set lat/lon are geocoded with OpenStreetMap Nominatim
(1 request/second, per their usage policy). Re-run after editing the source:

    python tools/build_walks.py
"""
import json
import pathlib
import time
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "walks-source.json"
OUT = ROOT / "data" / "walks.js"
UA = "augs-dogs/0.1 (personal friends' walk planner)"

# Rough box around RI plus the nearby parts of CT and MA, to reject geocodes that land somewhere silly.
AREA = {"lat": (40.9, 42.5), "lon": (-72.5, -70.7)}


def geocode(q):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
        {"q": q, "format": "json", "limit": 1, "countrycodes": "us"}
    )
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=20) as r:
        hits = json.load(r)
    time.sleep(1.1)
    if not hits:
        return None
    lat, lon = float(hits[0]["lat"]), float(hits[0]["lon"])
    if not (AREA["lat"][0] < lat < AREA["lat"][1] and AREA["lon"][0] < lon < AREA["lon"][1]):
        return None
    return round(lat, 5), round(lon, 5)


def main():
    walks = json.loads(SRC.read_text(encoding="utf-8"))
    missing = []
    for w in walks:
        if "lat" not in w:
            hit = geocode(w["q"])
            if hit:
                w["lat"], w["lon"] = hit
            else:
                missing.append(w["id"])
        w.pop("q", None)
        w.setdefault("flags", [])
    if missing:
        raise SystemExit("No coordinates for: " + ", ".join(missing) + " - add lat/lon by hand in the source.")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_walks.py from tools/walks-source.json - edit the source, not this file.\n"
        "window.WALKS = " + json.dumps(walks, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(walks)} walks to {OUT}")


if __name__ == "__main__":
    main()
